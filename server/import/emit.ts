// server/import/emit.ts — an outline into manuscript.md in the house shape
// (spec §7.9; the convert-manuscript skill): half-title, title page,
// copyright, contents, front matter, chapters with {dropcap}, back matter,
// colophon. Guesses carry a `%% check:` line above them.
import type { Block } from "./blocks.ts";
import type { Outline } from "./structure.ts";
import { slugify } from "./structure.ts";

const needsEscape = /^(-\s|\d+\.\s|%%|\{(?!\/?em\}))/;
const line = (t: string) => needsEscape.test(t) ? `\\${t}` : t;

export interface Emitted {
  manuscript: string;
  images: Record<string, Uint8Array>; // images/<file> → bytes
}

const everyBlock = (o: Outline): Block[] =>
  [
    ...o.front,
    ...o.back,
    ...o.body.flatMap((b) => b.kind === "part" ? [b, ...b.chapters] : [b]),
  ].flatMap((x) => x.content);

export function emit(o: Outline, today = new Date()): Emitted {
  const s = o.src;
  const out: string[] = [];
  const images: Record<string, Uint8Array> = {};
  const usedImages = new Set<string>();
  const noImageFiles = Object.keys(s.images).length === 0;
  const imageCount = everyBlock(o).filter((b) => b.kind === "image").length;
  const title = s.title ?? s.name.replace(/\.[^.]+$/, "");
  const date = today.toLocaleDateString("en-GB", {
    day: "numeric",
    month: "short",
    year: "numeric",
  });
  const pg = s.gutenberg;

  out.push(`%% Imported from ${s.name} on ${date}.`);
  for (const l of o.summary) out.push(`%% ${l}`);
  if (noImageFiles && imageCount) {
    out.push(
      `%% check: ${imageCount} illustration${
        imageCount === 1 ? "" : "s"
      } came without image files. Put them in images/ under the slugs below, or delete the {illustration} lines.`,
    );
  }
  out.push(`%% Lines marked "%% check:" are guesses. Type { to see every tag.`);
  out.push("");

  out.push("{matter: half-title}", "{title}", title, "");
  out.push("{matter: title-page}", "{title}", title);
  if (s.author) out.push("{author}", s.author);
  else {out.push(
      "%% check: the file names no author.",
      "{author}",
      "%% fill in",
    );}
  if (s.year) out.push("{year}", s.year);
  else {out.push(
      "%% check: the file gives no publication year. Fill it in or delete {year}.",
      "{year}",
      "%% fill in",
    );}
  out.push("");

  out.push("{matter: copyright}", "{copyright-line}");
  if (pg) {
    out.push(
      "This text is in the public domain.",
      "{rights}",
      `Sourced from Project Gutenberg eBook #${pg}. No rights reserved.`,
    );
  } else {
    out.push(
      "%% check: the copyright line is a guess from the file’s author and year.",
      `Copyright © ${s.year ?? today.getFullYear()} ${s.author ?? ""}`.trim(),
      "{rights}",
      "All rights reserved.",
    );
  }
  out.push("");
  out.push(
    "{matter: toc}",
    "{title}",
    "Contents",
    "%% auto-generated by renderer",
    "",
  );

  const image = (b: Extract<Block, { kind: "image" }>) => {
    const base = b.alt
      ? slugify(b.alt)
      : b.src
      ? slugify(b.src.replace(/\.[^.]+$/, ""))
      : "illustration";
    let slug = base, n = 2;
    while (usedImages.has(slug)) slug = `${base}-${n++}`;
    usedImages.add(slug);
    const data = s.images[b.src];
    if (data) {
      const ext = (b.src.match(/\.([a-z0-9]+)$/i)?.[1] ?? "jpg").toLowerCase();
      images[`images/${slug}.${ext}`] = data;
    } else if (!noImageFiles) {
      out.push(
        "%% check: no image file came with this illustration. Put one at images/" +
          slug + ".jpg or delete it.",
      );
    }
    out.push(`{illustration: ${slug} | placement: full-page}`);
    if (b.alt) out.push(line(b.alt));
  };

  const content = (blocks: Block[], dropcap: boolean) => {
    let first = dropcap;
    for (let i = 0; i < blocks.length; i++) {
      const b = blocks[i]!;
      if (b.check) out.push(`%% check: ${b.check}`);
      if (b.kind === "verse") {
        // Consecutive stanzas are one poem.
        out.push("{poem}");
        for (;;) {
          const v = blocks[i] as Extract<Block, { kind: "verse" }>;
          v.lines.forEach((l, k) =>
            out.push(line(l) + (k < v.lines.length - 1 ? "\\" : ""))
          );
          if (blocks[i + 1]?.kind !== "verse") break;
          out.push("");
          i++;
        }
        out.push("{/poem}", "");
        first = false;
        continue;
      }
      switch (b.kind) {
        case "para":
          if (first) out.push("{dropcap}");
          out.push(line(b.text));
          first = false;
          break;
        case "quote":
          out.push("{quote}", line(b.text), "{/quote}");
          break;
        case "heading":
          out.push(b.level <= 1 ? "{heading}" : "{subheading}", line(b.text));
          if (b.sub) out.push("{subheading}", line(b.sub));
          break;
        case "break":
          out.push("{break}");
          break;
        case "image":
          image(b);
          break;
      }
      out.push("");
    }
  };

  const section = (
    sec: { type: string; title?: string; content: Block[]; check?: string },
  ) => {
    if (sec.check) out.push(`%% check: ${sec.check}`);
    out.push(`{matter: ${sec.type}}`);
    if (sec.title) out.push("{title}", line(sec.title));
    else if (
      !["dedication", "epigraph", "copyright", "colophon"].includes(sec.type)
    ) {
      out.push("{title}", sec.type[0]!.toUpperCase() + sec.type.slice(1));
    }
    out.push("");
    content(sec.content, true);
  };

  for (const sec of o.front) section(sec);

  const chapter = (
    c: {
      slug: string;
      title?: string;
      subtitle?: string;
      content: Block[];
      check?: string;
    },
  ) => {
    if (c.check) out.push(`%% check: ${c.check}`);
    out.push(`{chapter: ${c.slug}}`);
    if (c.title) out.push("{title}", line(c.title));
    if (c.subtitle) out.push("{subtitle}", line(c.subtitle));
    out.push("");
    content(c.content, true);
  };
  for (const n of o.body) {
    if (n.kind === "part") {
      if (n.check) out.push(`%% check: ${n.check}`);
      out.push(`{part: ${n.slug}}`);
      if (n.title) out.push("{title}", line(n.title));
      out.push("");
      content(n.content, false);
      for (const c of n.chapters) chapter(c);
    } else chapter(n);
  }

  for (const sec of o.back) section(sec);

  out.push("{matter: colophon}", "{typeface}", "%% fill in", "{printer}");
  out.push(
    pg
      ? `Text from Project Gutenberg eBook #${pg} (gutenberg.org/ebooks/${pg}), a public-domain transcription.`
      : "%% fill in",
  );
  out.push("");

  // Collapse runs of blank lines left by empty content.
  const manuscript = out.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd() + "\n";
  return { manuscript, images };
}
