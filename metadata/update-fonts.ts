// metadata/update-fonts.ts — regenerates metadata/fonts-catalog.ts from Google
// Fonts' public catalog (the metadata behind fonts.google.com; no API key).
// Run with `deno task fonts` when new families should show in the picker.
const res = await fetch("https://fonts.google.com/metadata/fonts");
if (!res.ok) throw new Error(`catalog fetch failed: ${res.status}`);
const { familyMetadataList } = await res.json() as {
  familyMetadataList: Array<{
    family: string;
    category: string;
    subsets: string[];
    popularity: number;
  }>;
};

const CATEGORY: Record<string, string> = {
  "Serif": "serif",
  "Sans Serif": "sans",
  "Display": "display",
  "Handwriting": "script",
  "Monospace": "mono",
};
// A book needs Latin glyphs; families without them could not set its text.
const rows = familyMetadataList
  .filter((f) => f.subsets.includes("latin"))
  .sort((a, b) => a.popularity - b.popularity)
  .map((f) => {
    const cat = CATEGORY[f.category];
    if (!cat) throw new Error(`unknown category ${f.category} (${f.family})`);
    return `  [${JSON.stringify(f.family)}, "${cat}"],`;
  });

await Deno.writeTextFile(
  new URL("./fonts-catalog.ts", import.meta.url),
  `// metadata/fonts-catalog.ts — GENERATED by metadata/update-fonts.ts
// (\`deno task fonts\`); do not edit. Every Google Fonts family with Latin
// glyphs, most popular first, with its category for the picker's filters.
export type FontCategory = "serif" | "sans" | "display" | "script" | "mono";
export const FONT_CATALOG: Array<[family: string, category: FontCategory]> = [
${rows.join("\n")}
];
export const GOOGLE_FAMILIES: ReadonlySet<string> = new Set(
  FONT_CATALOG.map(([f]) => f),
);
`,
);
console.log(`${rows.length} families`);
